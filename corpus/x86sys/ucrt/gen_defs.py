#!/usr/bin/env python3
"""Turn apisets.txt into the .def files build.sh links with.

  ucrtbase.def          the union, exported from the one DLL that has the code
  <apiset>.def          one per section: every name forwarded to ucrtbase

A forwarder export ("malloc = ucrtbase.malloc") is resolved by the guest
loader's export_addr, which follows the "DLL.Symbol" text and looks the target
up among the already-mapped guest DLLs -- so each forwarder DLL also imports
ucrtbase's anchor, which is what gets it mapped. See fwd.c.
"""
import os
import sys


def parse(path):
    sections, cur = [], None
    for raw in open(path, encoding="utf-8"):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            cur = (line[1:-1], [])
            sections.append(cur)
            continue
        if cur is None:
            sys.exit(f"{path}: name before any [section]: {line!r}")
        # "export=symbol" names the internal symbol for an export that cannot
        # be spelled as a C identifier.
        name, _, sym = line.partition("=")
        cur[1].append((name.strip(), sym.strip() or None))
    return sections


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "out")
    sections = parse(os.path.join(here, "apisets.txt"))
    os.makedirs(out, exist_ok=True)

    # The union, in one place, so a name can only be exported once even when
    # two api sets share it (_beginthreadex is in both process and runtime).
    union = {}
    for _, names in sections:
        for name, sym in names:
            if name in union and union[name] != sym:
                sys.exit(f"apisets.txt: {name} mapped to two symbols")
            union[name] = sym

    with open(os.path.join(out, "ucrtbase.def"), "w", encoding="utf-8") as f:
        f.write("; GENERATED by gen_defs.py from apisets.txt -- do not edit.\n")
        f.write("LIBRARY ucrtbase.dll\nEXPORTS\n")
        f.write("_gh_ucrt_anchor\n")
        for name in sorted(union):
            sym = union[name]
            f.write(f"{name}={sym}\n" if sym else f"{name}\n")

    for dll, names in sections:
        base = dll[:-4] if dll.lower().endswith(".dll") else dll
        with open(os.path.join(out, base + ".def"), "w", encoding="utf-8") as f:
            f.write("; GENERATED by gen_defs.py from apisets.txt -- do not edit.\n")
            f.write(f"LIBRARY {dll}\nEXPORTS\n")
            for name, _ in names:
                f.write(f"{name}=ucrtbase.{name}\n")

    print(f"gen_defs: {len(sections)} forwarder DLLs, {len(union)} names")
    for dll, names in sections:
        print(f"  {dll:38s} {len(names):3d}")


if __name__ == "__main__":
    main()
