#!/usr/bin/env python3
"""Emit the loader's copy of the frozen bindless space registry.

templates.json is the single source of truth for which register space each
descriptor-heap resource type was lowered into. The loader has to build a root
signature that covers exactly those spaces, so generate that table rather than
maintaining a second hand-written list that can silently drift.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RANGE = {0: 'D3D12_DESCRIPTOR_RANGE_TYPE_SRV', 1: 'D3D12_DESCRIPTOR_RANGE_TYPE_UAV',
         2: 'D3D12_DESCRIPTOR_RANGE_TYPE_CBV', 3: 'D3D12_DESCRIPTOR_RANGE_TYPE_SAMPLER'}

t = json.load(open(os.path.join(HERE, 'templates.json')))
rows = sorted(((v['space'], v['cls'], k) for k, v in t.items()))
out = ['// GENERATED by toolchain/dxil/emit_spaces.py from templates.json -- do not edit.',
       '// One register space per distinct resource type reached through the SM 6.6',
       '// descriptor heap. Frozen: all lowered shaders share one root signature, so a',
       '// space that moved between shaders would need a different root signature per PSO.',
       '#pragma once',
       '',
       'struct GhBindlessSpace { D3D12_DESCRIPTOR_RANGE_TYPE type; UINT space; const char* what; };',
       '',
       'static const GhBindlessSpace kGhBindlessSpaces[] = {']
for space, cls, key in rows:
    out.append('    { %-38s %5d, "%s" },' % (RANGE[cls] + ',', space, key))
out += ['};', '',
        'static const UINT kGhBindlessSpaceBase = %d;' % rows[0][0],
        'static const UINT kGhBindlessSpaceCount = %d;' % len(rows), '']
p = os.path.join(HERE, '..', '..', 'src', 'loader', 'gh_dxil_spaces.h')
open(p, 'w').write('\n'.join(out))
print('wrote %s: %d spaces (%d..%d)' % (os.path.normpath(p), len(rows),
                                        rows[0][0], rows[-1][0]))
